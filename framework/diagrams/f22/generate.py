#!/usr/bin/env python3
"""Regenerate F22 D2 assets with an installed official d2 v0.9.0 CLI."""
import datetime,hashlib,json,pathlib,subprocess,sys
D=pathlib.Path(__file__).resolve().parent;R=D.parents[2]
cli=sys.argv[1] if len(sys.argv)>1 else 'd2'
version=subprocess.check_output([cli,'--version'],text=True).strip()
if version!='v0.9.0':raise RuntimeError('Expected official D2 v0.9.0, got '+version)
checks=[]
for slug in ['cycle','metrics']:
 p=D/(slug+'.d2')
 for args in [['fmt',str(p)],['fmt','--check',str(p)],['validate',str(p)]]+[["--layout=dagre",f"--theme={t}","--pad=24","--timeout=30",str(p),str(D/f'{slug}-{name}.svg')] for name,t in [('light',4),('dark',201)]]:
  run=subprocess.run([cli]+args,capture_output=True,text=True);checks.append({'command':[str(x).replace(str(R)+'/', '') for x in [cli]+args],'exit_code':run.returncode,'stdout':run.stdout,'stderr':run.stderr});run.check_returncode()
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
files=list(D.glob('*.d2'))+list(D.glob('*.svg'))
(D/'generation.json').write_text(json.dumps({'at':datetime.datetime.now(datetime.timezone.utc).isoformat(),'generator':version,'cli_sha256':sha(pathlib.Path(cli)),'layout':'dagre','themes':{'light':4,'dark':201},'artifact_edits':'D2 source only; generated by official CLI, no hand edited SVG','scope':'cycle arrows evaluation design dependency; metrics arrows reading sequence, Recall/nDCG independent; not ES internal execution','checks':checks,'sha256':{str(p.relative_to(R)):sha(p) for p in files}},ensure_ascii=False,indent=2)+'\n')
print('F22 D2 v0.9.0 fmt/validate/render/hash passed')
